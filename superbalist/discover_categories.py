"""
Category discovery helper
==========================
Reads Superbalist's own navigation menu (embedded in every page) and outputs the
full, correct list of CLOTHING category URLs — no guessing slugs, no dead ends.

It writes `category_urls.py` (a ready-to-use CATEGORY_URLS list) and prints a
paste-ready block. Drop the list into sync_catalogue.py, then run the sync.

RUN
    python discover_categories.py
"""

import re
import json
import requests

# ---------------------------------------------------------------------------
# CONFIG — tweak these to widen/narrow what counts as a clothing category
# ---------------------------------------------------------------------------
# Any Superbalist page carries the full menu; this one is just a reliable source.
SOURCE_PAGE = "https://superbalist.com/browse/men/tops/t-shirts-vests"

GENDERS = {"women", "men", "kids"}        # which top sections to keep

# Drop any category path containing these words (shoes, beauty, accessories…).
# Remove a word here to INCLUDE that category (e.g. delete "socks" to keep socks).
EXCLUDE = {
    "shoes", "sneaker", "trainer", "boots", "sandal", "heels", "pumps", "loafer",
    "slip-ons", "running", "accessor", "bag", "wallet", "jewellery", "eyewear",
    "headwear", "belts", "scarves", "watches", "beauty", "grooming", "fragrance",
    "haircare", "skincare", "nailcare", "nutricosmetic", "gift-sets", "face",
    "eyes", "lips", "socks", "underwear", "lingerie", "bras", "panties", "stockings",
}

OUTPUT_FILE = "category_urls.py"
BASE = "https://superbalist.com"
HEADERS = {
    "User-Agent": ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                   "AppleWebKit/537.36 (KHTML, like Gecko) "
                   "Chrome/125.0 Safari/537.36"),
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
}


# ---------------------------------------------------------------------------
def hydrate_factory(P):
    cache = {}

    def hydrate(i):
        if isinstance(i, int) and i < 0:
            return None
        if i in cache:
            return cache[i]
        v = P[i]
        if v is None or not isinstance(v, (list, dict)):
            cache[i] = v
            return v
        if isinstance(v, list):
            if len(v) > 0 and isinstance(v[0], str):
                o = [v[0]] + [hydrate(x) for x in v[1:]]
                cache[i] = o
                return o
            o = []
            cache[i] = o
            for n in v:
                o.append(hydrate(n))
            return o
        o = {}
        cache[i] = o
        for k, val in v.items():
            o[k] = hydrate(val)
        return o

    return hydrate


def collect_paths(menu):
    paths = set()

    def walk(n):
        if isinstance(n, dict):
            p = n.get("path")
            if isinstance(p, str) and p.startswith("/browse/") and "?" not in p:
                paths.add(p.rstrip("/"))
            walk(n.get("data"))
        elif isinstance(n, list):
            for x in n:
                walk(x)

    for section in menu:
        walk(section)
    return paths


def keep(path):
    segs = [s for s in path.split("/") if s]       # ['browse','men','tops','shirts']
    if len(segs) < 4:                               # leaf subcategories only
        return False
    if segs[1] not in GENDERS:
        return False
    low = path.lower()
    return not any(k in low for k in EXCLUDE)


def main():
    print(f"Reading menu from {SOURCE_PAGE}")
    resp = requests.get(SOURCE_PAGE, headers=HEADERS, timeout=20)
    resp.raise_for_status()

    m = re.search(r'id="__NUXT_DATA__"[^>]*>(.*?)</script>', resp.text, re.DOTALL)
    if not m:
        print("Could not find the embedded menu. Try a different SOURCE_PAGE.")
        return
    P = json.loads(m.group(1))
    hydrate = hydrate_factory(P)

    menu = None
    for i, raw in enumerate(P):
        if isinstance(raw, dict) and "megadropdown" in raw:
            menu = hydrate(i)["megadropdown"]
            break
    if not menu:
        print("No navigation menu found in this page.")
        return

    kept = sorted(p for p in collect_paths(menu) if keep(p))
    print(f"Found {len(kept)} clothing categories.")

    # Write a ready-to-use Python file
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by discover_categories.py\n")
        f.write("# Paste this list into sync_catalogue.py, or: from category_urls import CATEGORY_URLS\n\n")
        f.write("CATEGORY_URLS = [\n")
        for g in ("men", "women", "kids"):
            group = [p for p in kept if p.split("/")[2] == g]
            if group:
                f.write(f"    # {g} ({len(group)})\n")
                for p in group:
                    f.write(f'    "{BASE}{p}",\n')
        f.write("]\n")

    print(f"Wrote {OUTPUT_FILE}  ({len(kept)} URLs).")
    print("\nNext: open category_urls.py, copy the CATEGORY_URLS list, and paste it")
    print("over the CATEGORY_URLS list at the top of sync_catalogue.py. Then run:")
    print("    python sync_catalogue.py")


if __name__ == "__main__":
    main()
